import { existsSync } from 'node:fs';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = resolve(appRoot, 'dist-demo');
const markerPath = resolve(outputDirectory, '.2j-synthetic-demo-output');
const markerText = '2J synthetic fixture demo build\n';

if (existsSync(outputDirectory)) {
  const marker = await readFile(markerPath, 'utf8').catch(() => '');
  if (marker !== markerText) {
    throw new Error('Refusing to replace apps/client-app/dist-demo because it is not marked as generated by this script.');
  }
  await rm(outputDirectory, { recursive: true });
}

for (const key of Object.keys(process.env)) {
  if (key.startsWith('VITE_')) delete process.env[key];
}
process.env.VITE_2J_HUB_DEMO = 'true';
process.env.VITE_2J_BUILD_ID = 'synthetic-demo';

const emptyEnvDirectory = await mkdtemp(join(tmpdir(), '2j-home-demo-env-'));
try {
  const { build } = await import('vite');
  await build({
    root: appRoot,
    mode: 'demo',
    envDir: emptyEnvDirectory,
    build: { outDir: outputDirectory, emptyOutDir: true },
  });
  await writeFile(markerPath, markerText, { flag: 'wx' });
} finally {
  await rm(emptyEnvDirectory, { recursive: true, force: true });
}
